#!/usr/bin/env python3
"""Generate fo_catalog.h for the offline ZNetwork proxy from the reference catalog CSVs
(same data as the client's d3.Arch01 GameItem/MapInfo/FunctionItem tables).

usage: gen_catalog.py <catalog-data-dir> <out.h>
"""
import csv, sys, os, collections

src = sys.argv[1]; out = sys.argv[2]
def rd(name): return list(csv.DictReader(open(os.path.join(src, name), newline='')))
items = rd('GameItem.csv'); funcs = {r['FunctionIndex']: r for r in rd('FunctionItem.csv')}; maps = rd('MapInfo.csv')

MIRRORED = set([0x0B,0x0C]) | set(range(0x15,0x1A)) | set(range(0x1F,0x23)) | set(range(0x2A,0x2E)) | {0x30,0x31,0x51}
CUSTOM = set(range(0x3D,0x43))

def itype(r): return 0x0B + (int(r['HighGroup'])-1)*10 + (int(r['MiddleGroup'])-1)
def ftype(r):
    f = funcs.get(r['FunctionIndex']); return int(f['FunctionType']) if f else 0
def value(r):
    ut = int(r['UseType'])
    if ut == 2: return int(r['Durability'] or 0) or 1
    if ut == 5: return int(r['UseCount'] or 0) or 1
    if ut == 4: return int(r['UseTime'] or 0) or 2592000
    return 1
def prio(r):
    ut = int(r['UseType']); noitem = r['EngName'].endswith('_NoItem')
    base = {6:600, 1:500, 2:400, 5:300, 4:200}.get(ut, 100)
    if noitem: base -= 1000
    return base + (value(r) if ut in (5,4) else 0) / 1e7

# One owned instance per "base item": EngName before the first '_' (Mark Edwin_Period_24 / Mark Edwin_Permanent ->
# "Mark Edwin"), within the same High/Middle group. The best SKU wins (see prio()).
groups = collections.defaultdict(list)
for r in items: groups[(r['HighGroup'], r['MiddleGroup'], r['EngName'].split('_')[0].strip().lower())].append(r)
own = set()
for rep, rows in groups.items():
    cand = [r for r in rows if r['IsInvenShow'] == '1' and (itype(r) in MIRRORED or itype(r) in CUSTOM)]
    if not cand: continue
    best = max(cand, key=prio); own.add(best['ItemIndex'])

with open(out, 'w', newline='\n') as f:
    w = f.write
    w('// GENERATED by tools/gen_catalog.py from the reference catalog CSVs (== client d3.Arch01 data). DO NOT EDIT.\n')
    w('// FoCatItem: itemIndex, itemType (0x0B + (HighGroup-1)*10 + (MiddleGroup-1)), functionType (FunctionItem.csv),\n')
    w('//            slotCount (characters: perk slots), useType, defaultValue (durability/count/seconds), own (part of the default inventory),\n')
    w('//            pointPrice, cashPrice.\n')
    w('#pragma once\n#include <cstdint>\n\n')
    w('struct FoCatItem { uint32_t itemIndex; uint8_t itemType; uint8_t functionType; uint8_t slotCount; uint8_t useType; uint32_t defaultValue; uint8_t own; uint32_t pointPrice; uint32_t cashPrice; };\n')
    w('static const FoCatItem g_FoCatalog[] = {\n')
    n = 0; nown = 0; ncust = 0
    for r in items:
        it = itype(r)
        o = 1 if r['ItemIndex'] in own else 0
        if o and it in CUSTOM: ncust += 1
        nown += o
        w('  {%s, 0x%02X, %d, %d, %d, %d, %d, %s, %s}, // %s\n' % (r['ItemIndex'], it, ftype(r), int(r['SlotCount'] or 0), int(r['UseType']), value(r), o, r['PointPrice'] or 0, r['CashPrice'] or 0, r['EngName'].replace('\\','/')[:48]))
        n += 1
    w('};\nstatic const size_t g_FoCatalogCount = %d;   // owned by default: %d (of which custom parts: %d)\n\n' % (n, nown, ncust))
    w('struct FoCatMap { uint16_t mapIndex; uint8_t mapMode; uint8_t userDefault; uint8_t timeDefault; uint16_t killDefault; uint8_t roundDefault; uint8_t weapon; const char* mapName; const char* modeName; };\n')
    w('static const FoCatMap g_FoMaps[] = {\n')
    for m in maps:
        w('  {%s, %s, %s, %s, %s, %s, %s, "%s", "%s"},\n' % (m['MapIndex'], m['MapMode'], m['UserDefault'] or 0, m['TimeDefault'] or 0, m['KillDefault'] or 0, m['RoundDefault'] or 0, m['Weapon'] or 0, m['MapName'], m['ModeName']))
    w('};\nstatic const size_t g_FoMapCount = %d;\n' % len(maps))
print('items', n, 'own', nown, 'custom', ncust, 'maps', len(maps))
