#!/usr/bin/env python3
r"""
cleanup.py -- clean the fearonline project tree of build leftovers, parallel
DLL builds, crash dumps and stale logs.

    python tools\cleanup.py                 # DRY RUN: show what would go (default)
    python tools\cleanup.py --apply         # actually delete (asks for confirmation)
    python tools\cleanup.py --apply --yes   # no confirmation
    python tools\cleanup.py --apply --fear2 # also drop trash\Fear2_Game (1 GB, FEAR 2 files)
    python tools\cleanup.py --apply --venvs # also drop NewLauncher\venv, NewServer\venv (recreate: pip install -r requirements.txt)
    python tools\cleanup.py --git-gc        # run `git gc --prune=now` (reclaims ~3.8 GB of stale pack garbage)
    python tools\cleanup.py --gitignore     # append the new ignore patterns to .gitignore

Rules (what is KEPT in NewZNetwork): znetwork_proxy.cpp, znetwork_proxy.def,
build.bat, DEBUGGING.md, ZNetwork.dll (the last good build).
Everything else there is a regenerable build product, an abandoned parallel
build (asan / asan_vs2022 / diagnostic_build) or a crash dump.
"""
import argparse, hashlib, os, shutil, subprocess, sys, time

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

# (relative path, reason). Directories are removed recursively.
ALWAYS = [
    # --- NewZNetwork: parallel builds / intermediates / dumps / logs ---
    ("NewZNetwork/asan",                      "abandoned ASan build (0-byte DLL, obj, pdb)"),
    ("NewZNetwork/asan_vs2022",               "abandoned ASan VS2022 build"),
    ("NewZNetwork/diagnostic_build",          "October diagnostic builds + copied WinDbg x86 + old DLL snapshots"),
    ("NewZNetwork/crashes",                   "full-memory crash dumps (~1.6 GB), analysed already"),
    ("NewZNetwork/build_asan.bat",            "ASan build script (builds into the removed dir)"),
    ("NewZNetwork/asan_exports.txt",          "export-list comparison dump"),
    ("NewZNetwork/exports_game.txt",          "export-list comparison dump"),
    ("NewZNetwork/exports_new.txt",           "export-list comparison dump"),
    ("NewZNetwork/normal_exports.txt",        "export-list comparison dump"),
    ("NewZNetwork/vc140.pdb",                 "compiler pdb from a /Zi build"),
    ("NewZNetwork/znetwork_proxy.obj",        "build intermediate (regenerated by build.bat)"),
    ("NewZNetwork/znetwork_proxy.exp",        "build intermediate (regenerated by build.bat)"),
    ("NewZNetwork/znetwork_proxy.lib",        "build intermediate (regenerated by build.bat)"),
    # --- root ---
    ("__pycache__",                           "python cache"),
    ("NewLauncher/__pycache__",               "python cache"),
    ("znetwork_proxy_log.txt",                "live proxy log (rewritten on every game start)"),
    # --- trash ---
    ("trash/strings.log",                     "old strings dump"),
    ("trash/znetwork_proxy_log.txt",          "old proxy log copy"),
    ("trash/engine_strings.txt",              "duplicate of C:\\games\\...\\Game\\engine_strings.txt"),
]

# removed only if its content hash equals the other file's (safety check)
DUPLICATES = [
    ("trash/decompiles/decompiled_engine.c", "trash/decompiles/decompiled_gameclient.c",
     "byte-identical duplicate of the GameClient decompile (26 MB)"),
]

OPTIONAL = {
    "fear2": [("trash/Fear2_Game", "FEAR 2 game files (1 GB) -- unrelated to FEAR Online reversing")],
    "venvs": [("NewLauncher/venv", "python venv (302 MB) -- `pip install -r requirements.txt` recreates it"),
              ("NewServer/venv",   "python venv -- recreate the same way")],
}

GITIGNORE_ADD = """
# --- added by tools/cleanup.py (2026-11-03) ---
NewZNetwork/crashes/
NewZNetwork/asan*/
NewZNetwork/diagnostic_build/
*.dmp
*.pdb
*.ilk
*.map
*_exports.txt
znetwork_proxy_log.txt
"""

def size_of(path):
    if os.path.isfile(path):
        return os.path.getsize(path)
    total = 0
    for dp, _, fns in os.walk(path):
        for f in fns:
            try: total += os.path.getsize(os.path.join(dp, f))
            except OSError: pass
    return total

def human(n):
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB": return f"{n:.1f} {unit}" if unit != "B" else f"{n} B"
        n /= 1024.0

def sha1(path):
    h = hashlib.sha1()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()

def on_rm_error(func, path, exc_info):
    try:
        os.chmod(path, 0o666); func(path)
    except Exception as e:
        print(f"    ! could not remove {path}: {e}")

def remove(path):
    if os.path.isdir(path) and not os.path.islink(path):
        shutil.rmtree(path, onerror=on_rm_error)
    else:
        os.chmod(path, 0o666); os.remove(path)

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--apply", action="store_true", help="delete (default is dry run)")
    ap.add_argument("--yes", action="store_true", help="do not ask for confirmation")
    ap.add_argument("--fear2", action="store_true", help="also remove trash/Fear2_Game")
    ap.add_argument("--venvs", action="store_true", help="also remove the python venvs")
    ap.add_argument("--git-gc", action="store_true", help="run git gc --prune=now afterwards")
    ap.add_argument("--gitignore", action="store_true", help="append new patterns to .gitignore")
    args = ap.parse_args()

    os.chdir(ROOT)
    plan = []
    for rel, why in ALWAYS:
        if os.path.exists(rel): plan.append((rel, why))
    for dup, keep, why in DUPLICATES:
        if os.path.exists(dup) and os.path.exists(keep):
            print(f"hashing {dup} vs {keep} ...")
            if sha1(dup) == sha1(keep): plan.append((dup, why))
            else: print(f"    files differ -- keeping {dup}")
    for flag, items in OPTIONAL.items():
        if getattr(args, flag):
            for rel, why in items:
                if os.path.exists(rel): plan.append((rel, why))
        else:
            for rel, why in items:
                if os.path.exists(rel):
                    print(f"(skipped, use --{flag}) {rel:45s} {human(size_of(rel)):>10s}  {why}")

    print()
    total = 0
    for rel, why in plan:
        sz = size_of(rel); total += sz
        kind = "dir " if os.path.isdir(rel) else "file"
        print(f"{kind}  {rel:45s} {human(sz):>10s}  {why}")
    print(f"\n{len(plan)} items, {human(total)} total")

    if not args.apply:
        print("\nDRY RUN -- nothing deleted. Re-run with --apply to delete.")
    else:
        if not args.yes:
            ans = input("\nDelete these? [y/N] ").strip().lower()
            if ans != "y":
                print("aborted"); return 1
        report = [f"cleanup {time.strftime('%Y-%m-%d %H:%M:%S')} root={ROOT}"]
        for rel, why in plan:
            try:
                remove(rel); print(f"removed  {rel}"); report.append(f"removed {rel}")
            except Exception as e:
                print(f"FAILED   {rel}: {e}"); report.append(f"FAILED {rel}: {e}")
        os.makedirs("tools", exist_ok=True)
        with open(os.path.join("tools", "cleanup_report.txt"), "a", encoding="utf-8") as f:
            f.write("\n".join(report) + "\n")
        print(f"\nfreed ~{human(total)}; report appended to tools\\cleanup_report.txt")

    if args.gitignore:
        with open(".gitignore", "r+", encoding="utf-8") as f:
            cur = f.read()
            if "tools/cleanup.py" not in cur:
                f.write(GITIGNORE_ADD); print(".gitignore updated")
            else:
                print(".gitignore already has the patterns")

    if args.git_gc:
        print("\ngit gc --prune=now (this can take a few minutes on a 2.5 GB pack) ...")
        subprocess.run(["git", "count-objects", "-vH"])
        subprocess.run(["git", "gc", "--prune=now"])
        subprocess.run(["git", "count-objects", "-vH"])
    return 0

if __name__ == "__main__":
    sys.exit(main())
